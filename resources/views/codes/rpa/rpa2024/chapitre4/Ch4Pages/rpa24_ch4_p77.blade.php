            <div id="rpa-art-4.1.1" style="scroll-margin-top: 100px;">
                <h3 class="rpa-h3">4.1.1 Méthodes utilisables</h3>
                <p class="mb-4">Le calcul des forces sismiques peut être mené suivant trois méthodes :</p>
                <ul class="rpa-list-disc mb-4">
                    <li>la méthode statique équivalente ;</li>
                    <li>la méthode d'analyse modale spectrale ;</li>
                    <li>la méthode d'analyse dynamique par accélérogrammes.</li>
                </ul>
                
                <div class="rpa-comment mb-6">
                    <p class="italic text-gray-600">
                        <b>Commentaire :</b> La méthode statique non linéaire, cf. Annexe J, repose sur une analyse en poussée progressive sous l'effet de charges gravitaires constantes et de charges horizontales augmentant de manière monotone. Cette méthode permet de vérifier les performances structurelles des bâtiments, d'anticiper les mécanismes plastiques attendus et d'évaluer la répartition des dommages.
                    </p>
                </div>
            </div>

            <div id="rpa-art-4.1.2" style="scroll-margin-top: 100px;">
