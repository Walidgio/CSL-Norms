                <p class="mb-4">La méthode statique équivalente peut être utilisée dans les conditions suivantes :</p>
                <div class="rpa-indent space-y-4">
                    <p><b>a)</b> Le bâtiment, ou bloc étudié, satisfait aux conditions de régularité en plan et, en élévation prescrites au <a href="#rpa-art-3.7" class="rpa-link">§ 3.7</a>, avec une hauteur au plus égale à 65m en zones (I, II et III) et à 32 m en zones (IV, V et VI) ;</p>
                    <p><b>b)</b> Le bâtiment, ou bloc étudié, présente une configuration irrégulière tout en respectant, outre les conditions de hauteur énoncées en a), les conditions complémentaires indiquées au Tableau (4.1).</p>
