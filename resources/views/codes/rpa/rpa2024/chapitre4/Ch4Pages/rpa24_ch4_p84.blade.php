        <h2 class="rpa-h2" style="color: #c05621;">4.5 Prescriptions communes aux méthodes d'analyse</h2>
        
        <div id="rpa-art-4.5.1" style="scroll-margin-top: 100px;">
            <h3 class="rpa-h3">4.5.1 Justification de la sécurité</h3>
            <p class="text-justify mb-4">
                La sécurité de la structure vis-à-vis de l'action sismique doit être justifiée en vérifiant que les éléments structuraux et non structuraux satisfont aux critères de résistance et de déformation définis dans les chapitres correspondants.
            </p>
        </div>

        <div id="rpa-art-4.5.2" style="scroll-margin-top: 100px;">
            <h3 class="rpa-h3">4.5.2 Combinaison des actions sismiques</h3>
            <p class="text-justify mb-4">
                Pour tenir compte de la concomitance des composantes horizontales de l'action sismique, les effets maximaux dans la structure doivent être calculés en combinant les effets des actions agissant selon deux directions orthogonales (x et y) de la manière suivante :
            </p>

            <div class="rpa-equation-container" id="rpa-eqt-4.11">
                <div class="rpa-equation">
                    <math xmlns="http://www.w3.org/1998/Math/MathML" display="block">
                        <mrow>
                            <mi>E</mi>
                            <mo>=</mo>
                            <msub><mi>E</mi><mi>x</mi></msub>
                            <mo>+</mo>
                            <mn>0.3</mn>
                            <mo>&sdot;</mo>
                            <msub><mi>E</mi><mi>y</mi></msub>
                        </mrow>
                    </math>
                </div>
                <div class="rpa-eq-num">(4.11)</div>
            </div>

            <p class="text-center italic">et</p>

            <div class="rpa-equation-container" id="rpa-eqt-4.12">
                <div class="rpa-equation">
                    <math xmlns="http://www.w3.org/1998/Math/MathML" display="block">
                        <mrow>
                            <mi>E</mi>
                            <mo>=</mo>
                            <mn>0.3</mn>
                            <mo>&sdot;</mo>
                            <msub><mi>E</mi><mi>x</mi></msub>
                            <mo>+</mo>
                            <msub><mi>E</mi><mi>y</mi></msub>
                        </mrow>
                    </math>
                </div>
                <div class="rpa-eq-num">(4.12)</div>
            </div>

            <p class="mt-4 text-justify">
                où <i>E<sub>x</sub></i> et <i>E<sub>y</sub></i> sont les effets des actions sismiques agissant respectivement selon les directions x et y.
            </p>
        </div>

        <div id="rpa-art-4.5.3" class="mt-8" style="scroll-margin-top: 100px;">
            <h3 class="rpa-h3">4.5.3 Justification du comportement non linéaire</h3>
            <p class="text-justify mb-4">
                Dans le cas d'une analyse linéaire (statique équivalente ou modale spectrale), le comportement non linéaire de la structure est pris en compte globalement par le coefficient de comportement R (défini au <a href="#rpa-art-3.6" class="rpa-inline-link">&sect; 3.6</a>). Les déplacements calculés sous l'action sismique de calcul doivent être multipliés par le coefficient R pour obtenir les déplacements réels prévisibles.
            </p>
            <p class="text-justify mb-4">Le déplacement relatif d'étage <i>Δ<sub>k</sub></i>, au niveau <i>k</i>, est donné par :</p>
            <div class="rpa-equation-container" id="rpa-eqt-4.16">
                <div class="rpa-equation">
                    <math xmlns="http://www.w3.org/1998/Math/MathML" display="block">
                        <mrow>
                            <msub><mi>&Delta;</mi><mi>k</mi></msub>
                            <mo>=</mo>
                            <mi>R</mi>
                            <mo>&sdot;</mo>
                            <msub><mi>&delta;</mi><mi>k</mi></msub>
                        </mrow>
                    </math>
                </div>
                <div class="rpa-eq-num">(4.16)</div>
            </div>
            <p class="text-justify text-sm mb-0">où <i>δ<sub>k</sub></i> est le déplacement relatif d'étage issu de l'analyse linéaire élastique de calcul au niveau <i>k</i>.</p>
        </div>

        <div id="rpa-art-4.5.4" class="mt-8" style="scroll-margin-top: 100px;">
            <h3 class="rpa-h3">4.5.4 Résistance des éléments structuraux</h3>
            <p class="text-justify mb-4">
                La résistance des éléments structuraux doit être vérifiée sous les combinaisons d'actions appropriées (incluant les actions permanentes, d'exploitation et sismiques) définies dans les règlements de calcul en vigueur (DTR BC 2.41, etc.).
            </p>
        </div>
