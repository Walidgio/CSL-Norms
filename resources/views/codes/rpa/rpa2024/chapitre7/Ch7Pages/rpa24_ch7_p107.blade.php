            <span>7.2 <span class="text-gray-900 dark:text-gray-100">SP&Eacute;CIFICATIONS CONCERNANT LES MAT&Eacute;RIAUX</span></span>
        </h2>

        <h3 class="rpa-h3" id="rpa-art-7.2.1">7.2.1 <span class="text-gray-900 dark:text-gray-100">B&eacute;ton</span></h3>
        <p class="text-justify">
            Pour les &eacute;l&eacute;ments principaux, le b&eacute;ton d'une classe inf&eacute;rieure &agrave; C20/25 ne doit pas &ecirc;tre utilis&eacute;, au niveau de la conception et de la r&eacute;alisation, pour des b&acirc;timents &agrave; implanter en toute zone sismique autre que la zone 0.
        </p>
        <p class="text-justify indent-[20px] mt-4">
            Les valeurs des modules d'&eacute;lasticit&eacute; doivent &ecirc;tre conformes &agrave; celles fix&eacute;es par le C.B.A.
        </p>

        <h3 class="rpa-h3 mt-6" id="rpa-art-7.2.2">7.2.2 <span class="text-gray-900 dark:text-gray-100">Acier</span></h3>
        <p class="text-justify">
            Les armatures longitudinales et transversales des &eacute;l&eacute;ments principaux en b&eacute;ton arm&eacute; doivent &ecirc;tre &agrave; haute adh&eacute;rence, avec une limite caract&eacute;ristique d'&eacute;lasticit&eacute; sp&eacute;cifi&eacute;e sup&eacute;rieure ou &eacute;gale &agrave; 400&nbsp;MPa et inf&eacute;rieure ou &eacute;gale &agrave; 600&nbsp;MPa. La valeur caract&eacute;ristique de la d&eacute;formation relative sous charge maximale doit &ecirc;tre sup&eacute;rieure ou &eacute;gale &agrave; 5&nbsp;%.
        </p>
    </div>

