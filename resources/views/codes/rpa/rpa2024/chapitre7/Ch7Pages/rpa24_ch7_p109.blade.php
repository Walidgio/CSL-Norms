    <div class="rpa-bullet" style="margin-top: 15px;">• <i>l<sub>cl</sub></i> (unités: cm): la longueur libre du poteau</div>
    <p style="text-align: justify; margin-top: 10px;">
        Si <i>l<sub>cl</sub>/h<sub>c</sub> &lt; 3</i>: la hauteur totale du poteau doit être considérée comme zone critique et doit être munie d'armatures en conséquence.
    </p>

    <p style="text-indent: 20px; text-align: justify; margin-top: 15px;">
        Dans les deux premiers étages des bâtiments, les armatures de confinement doivent se prolonger au-delà des zones critiques d'une longueur égale à la moitié de la longueur de ces zones. Cette spécification concerne les systèmes de contreventement (1) et (2) (cf. <a href="#rpa-art-3.5" class="rpa-link">§ 3.5</a>) situés en zones sismiques IV, V et VI.
    </p>

    <div class="rpa-h2-black" style="font-style: italic; font-weight: normal; margin-top: 20px;">Effets locaux dus aux remplissages en maçonnerie ou en béton :</div>
    <p style="text-indent: 20px; text-align: justify;">
        A cause de la vulnérabilité particulière des murs de remplissage des rez-de-chaussée, une irrégularité induite par le séisme doit être envisagée à ces niveaux. Il convient, alors, de prendre des dispositions particulières. En l'absence de méthode plus précise, il y a lieu de considérer la hauteur totale des poteaux du rez-de-chaussée comme la longueur critique et de la confiner en conséquence. Cette condition est applicable dans le cas du système de contreventement (3) (cf. <a href="#rpa-art-3.5" class="rpa-link">§ 3.5</a>) situé dans les zones de sismicité IV, V et VI.
    </p>

    <div class="rpa-h2-black" id="rpa-art-7.4.2-long" style="margin-top: 20px;">Armatures longitudinales</div>
    <p style="text-align: justify;">
        Les armatures longitudinales doivent être à haute adhérence, droites et sans crochets :
    </p>
    
    <div class="rpa-bullet">• Leur pourcentage minimal sera de :</div>
    <div class="rpa-indent-2">- 0.8% en zones I et II</div>
    <div class="rpa-indent-2">- 0.9% en zone III</div>
    <div class="rpa-indent-2">- 1.0% en zones IV, V et VI</div>
    
    <div class="rpa-bullet mt-2">• Leur pourcentage maximal sera de:</div>
    <div class="rpa-indent-2">- 4% en zone courante</div>
    <div class="rpa-indent-2">- 8% en zone de recouvrement</div>
    
    <div class="rpa-bullet mt-2">• Le diamètre minimum est de : 12 mm</div>
    
    <div class="rpa-bullet mt-2">• La longueur minimale des recouvrements de barres longitudinales, de diamètre <i>&phi;<sub>l</sub></i>, est de:</div>
    <div class="rpa-indent-2">- 50 <i>&phi;<sub>l</sub></i> en zones I, II et III</div>
    <div class="rpa-indent-2">- 60 <i>&phi;<sub>l</sub></i> en zones IV, V et VI</div>
    
    <div class="rpa-bullet mt-2">• La distance entre les barres verticales, dans une face du poteau, ne doit pas dépasser :</div>
    <div class="rpa-indent-2">- 20 cm en zones I, II et III</div>
    <div class="rpa-indent-2">- 15 cm en zones IV, V et VI</div>

    <p style="text-indent: 20px; text-align: justify; margin-top: 20px;">
        Au moins une armature intermédiaire doit être prévue entre les armatures d'angle le long de chaque face du poteau, pour assurer l'intégrité des nœuds poteau-poutre (cf. <a href="#rpa-fig-7.2" class="rpa-link">Figure (7.2a)</a>).
    </p>
    <p style="text-indent: 20px; text-align: justify;">
        Dans les zones critiques des poteaux, des armatures, à haute adhérence, de confinement et des étriers d'au moins 6 mm de diamètre doivent être prévues avec un espacement suffisant pour assurer un minimum de ductilité et empêcher le flambement local des barres longitudinales.
    </p>
    <p style="text-indent: 20px; text-align: justify;">
        Les jonctions par recouvrement doivent être faites, si possible, à l'extérieur des zones nodales (zones critiques).
    </p>
    <p style="text-indent: 20px; text-align: justify;">
        La zone nodale est constituée par le nœud poteau-poutre, proprement dit, et les extrémités des éléments (poutres et poteaux) qui y concourent (cf. <a href="#rpa-fig-7.2" class="rpa-link">Figure (7.2b)</a>). Les longueurs à prendre en compte, pour chaque barre, sont données par <a href="#rpa-eqt-7.2" class="rpa-link">Eqn. (7.2)</a>.
    </p>
    <p style="text-indent: 20px; text-align: justify;">
        La longueur d'ancrage des armatures des poutres et des poteaux ancrées dans les n&oelig;uds poteaux-poutres doit être mesurée à partir d'un point de l'armature situé à une distance de (5<i>&phi;<sub>l</sub></i>) de la face du n&oelig;ud, vers l'intérieur du n&oelig;ud, pour prendre en compte l'extension de la zone plastifiée due aux déformations cycliques post-élastiques.
    </p>
