            <div id="rpa-art-7.5.2" class="rpa-h3" style="margin-top: 40px;">7.5.2 Ferraillage</div>
            <div class="rpa-h3-bold">Exigences de ductilité pour la zone critique</div>
            <p style="text-align: justify;">
                Les zones d'une poutre qui s'étendent sur une distance (<i>l' = 1.5h</i>) depuis la section transversale d'extrémité où la poutre est connectée à un nœud poteau-poutre, ainsi que de part et d'autre de toute autre section transversale susceptible de plastification dans la situation sismique de calcul, doivent être considérées comme des zones critiques, <i>h</i> étant la hauteur de la poutre (cf. <a href="#rpa-fig-7.2" class="rpa-link">Figure (7.2b)</a>).
            </p>

            <div class="rpa-h3-bold" style="margin-top: 20px;">Armatures longitudinales</div>
            <p style="text-align: justify;">
                Le pourcentage total minimum des aciers longitudinaux, sur toute la longueur de la poutre, est de 0,5% en toute section.
            </p>
            <p style="text-align: justify;">
                Le pourcentage total maximum des aciers longitudinaux est de :
            </p>
            <div class="rpa-indent">
                <div class="rpa-bullet">• 4% en zone courante</div>
                <div class="rpa-bullet">• 6% en zone de recouvrement</div>
