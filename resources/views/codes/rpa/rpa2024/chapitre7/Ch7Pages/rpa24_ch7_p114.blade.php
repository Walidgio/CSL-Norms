    <div class="rpa-header">
        <span class="chapter">Chapter 7. STRUCTURES EN BETON ARME</span>
        <span>114</span>
    </div>

    <div class="rpa-indent">
        <div class="rpa-bullet">• Au moins deux barres d'aciers longitudinaux, à haute adhérence de diamètre 12 mm (dans les zones IV, V et VI), doivent être placées sur les faces supérieure et inférieure, sur la longueur totale de la poutre ;</div>
        <div class="rpa-bullet">• Un quart de la section maximale d'armatures supérieures sur appuis est prolongée sur toute la longueur de la poutre.</div>
    </div>

    <p style="text-align: justify; text-indent: 20px;">
        Les poutres, supportant de faibles charges verticales, et sollicitées principalement, par les forces latérales sismiques, doivent avoir des armatures symétriques avec une section, en travée, au moins égale à la moitié de la section sur appui.
    </p>

    <p style="text-align: justify; text-indent: 20px;">
        La longueur minimale de recouvrement des barres longitudinales, de diamètre <i>&phi;<sub>l</sub></i>, est de :
    </p>
    <div class="rpa-indent">
        <div class="rpa-bullet">• (50<i>&phi;<sub>l</sub></i>) en zones I, II et III</div>
        <div class="rpa-bullet">• (60<i>&phi;<sub>l</sub></i>) en zones IV, V et VI</div>
    </div>

    <p style="text-align: justify; text-indent: 20px;">
        L'ancrage des armatures longitudinales, supérieures et inférieures dans les poteaux de rive et d'angle, doit être effectué conformément à la <a href="#rpa-fig-7.5" class="rpa-link">Figure (7.5)</a> avec des crochets à 90°. Cette même figure illustre les autres dispositions constructives et quantités minimales d'armatures.
    </p>

    <div class="rpa-h2-black" style="margin-top: 25px;">Armatures transversales</div>
    <p style="text-align: justify;">
        Le diamètre &phi;<sub>t</sub> des armatures, à haute adhérence, de confinement ne doit pas être inférieur à 6 mm.
    </p>
    <p style="text-align: justify; text-indent: 20px;">
        La quantité d'armatures transversales minimales est donnée par :
    </p>

    <div class="rpa-equation-container" id="rpa-eqt-7.7">
        <div class="rpa-equation">
            A<sub>t</sub> = (0.003).s.b
        </div>
        <div class="rpa-eq-num">(7.7)</div>
    </div>

    <p style="text-align: justify;">
        L'espacement maximum, entre les armatures transversales, est déterminé comme suit :
    </p>
    <div class="rpa-indent">
        <div class="rpa-bullet">• Dans les zones critiques:</div>
        <div class="rpa-indent">
            s = min(<i>h</i>/4 ; 24<i>&phi;<sub>t</sub></i> ; 17.5 cm ; 6<i>&phi;<sub>l</sub></i>) avec:<br>
            <div class="rpa-bullet">- <i>h</i> : hauteur de la poutre</div>
            <div class="rpa-bullet">- <i>&phi;<sub>t</sub></i> : diamètre des armatures de confinement</div>
            <div class="rpa-bullet">- <i>&phi;<sub>l</sub></i> : diamètre minimal des barres longitudinales</div>
        </div>
        <div class="rpa-bullet mt-2">• En dehors de la zone critique:</div>
        <div class="rpa-indent">
            s' &le; <i>h</i>/2<br>
            avec :<br>
            s' = min(<i>h</i>/4 ; 12<i>&phi;<sub>l</sub></i>) si les armatures comprimées sont nécessaires
        </div>
    </div>

    <p style="text-align: justify; margin-top: 15px;">
        <i>&phi;<sub>l</sub></i>: plus petit diamètre utilisé parmi les armatures longitudinales. Dans le cas d'une section en travée, avec armatures comprimées, c'est le plus petit diamètre utilisé parmi les aciers comprimés.
    </p>
    <p style="text-align: justify; text-indent: 20px;">
        Les premières armatures transversales doivent être disposées à 5 cm, au plus, du nu de l'appui ou de l'encastrement.
    </p>
