        <div id="rpa-art-7.1" style="scroll-margin-top: 100px;">
             <h2 class="rpa-h2">7.1 Généralités</h2>
             
             <div class="rpa-h3" id="rpa-art-7.1.1">7.1.1 Objet</div>
             <p style="text-indent: 20px; text-align: justify;">
                 Dans ce chapitre sont développées les prescriptions et indications nécessaires au dimensionnement des structures ou éléments de structures, en béton armé coulé en place de classe de résistance maximale C90/105, ainsi que les dispositions constructives les concernant. Les classes de résistance sont basées sur la résistance caractéristique mesurée sur cylindre/cube, <i>f<sub>ck</sub></i>, déterminée à 28 jours.
             </p>
             <p style="text-indent: 20px; text-align: justify;">
                 Pour les structures en béton armé préfabriquées, il y a lieu de se référer au <a href="#rpa-art-2.5.3" class="rpa-link">§ 2.5.3</a>.
             </p>
             <p style="text-indent: 20px; text-align: justify;">
                 Par ailleurs, les systèmes constructifs utilisant les planchers dits "planchers-dalles" ou "planchers champignons" sont prohibés en zone sismique.
             </p>

             <p style="text-align: justify; margin-top: 15px;">
                 <i>Commentaire (1) : Rappelons que ces derniers systèmes concernent les bâtiments à un ou plusieurs étages dont les planchers sont constitués par des dalles continues, sans nervures, supportées directement par des poteaux, sauf éventuellement sur les rives, le long desquelles peuvent exister des voiles porteurs ou des poutres en saillie au-dessous des dalles. Les dalles peuvent, éventuellement, être prolongées en porte-à-faux au-delà des poteaux de rive.</i>
             </p>
             <p style="text-align: justify; margin-top: 10px;">
                 <i>Les poteaux sont ou non pourvus, à chaque étage, de têtes épanouies, en forme générale de troncs de cône ou de pyramides renversées, appelés « chapiteaux ». Lorsque les chapiteaux existent, les planchers sont dits « planchers champignons » ; dans le cas contraire, il s'agit de « planchers dalles ».</i>
             </p>

             <p style="text-align: justify; margin-top: 15px;">
                 <i>Commentaire (2) : Pour la conception et le calcul des constructions en béton armé (ou en béton peu armé), les règles y afférentes (DTR BC 2.41 et DTR BC 2.42) s'appliquent; les présentes prescriptions sont additionnelles à celles contenues dans les documents précités, lorsque ces constructions se trouvent en zones sismiques I à VI.</i>
             </p>

             <div class="rpa-h3" id="rpa-art-7.1.2" style="margin-top: 25px;">7.1.2 Eléments principaux - Eléments secondaires</div>
             <p style="text-indent: 20px; text-align: justify;">
                 Dans ce qui suit, sont désignés, sous le nom d'éléments principaux, les éléments qui interviennent dans la résistance aux actions sismiques d'ensemble ou dans la distribution de ces actions, au sein de l'ouvrage.
             </p>
        </div>
