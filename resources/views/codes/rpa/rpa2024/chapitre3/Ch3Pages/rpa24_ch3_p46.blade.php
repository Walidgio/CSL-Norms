        <p class="text-justify italic mb-4 leading-relaxed">
            <span class="font-bold">Commentaire (1) :</span> Les zones, de très faible sismicité, sont celles où l'accélération de calcul au niveau d'un sol de classe S<sub>1</sub>, (A.g), ne dépasse pas 0.04 g (0.39 m / s<sup>2</sup>) où g est l'accélération de la pesanteur.
        </p>
        <p class="text-justify italic mb-6 leading-relaxed">
            <span class="font-bold">Commentaire (2) :</span> Les zones, de sismicité faible, sont celles où l'accélération de calcul, au niveau d'un sol de classe S<sub>1</sub>, (A.g), ne dépasse pas 0.07 g (0.69 m / s<sup>2</sup>).
        </p>

        <p class="text-justify mb-6 leading-relaxed">
            La <a href="#rpa-fig-3.1" class="rpa-inline-link">Figure (3.1)</a> représente la carte des zones sismiques de l'Algérie et le zonage global des différentes wilayas. L'annexe A donne la classification sismique par wilaya et par commune lorsque la wilaya est partagée entre plusieurs zones sismiques différentes.
        </p>

        <p class="text-justify italic mb-4 leading-relaxed">
            <span class="font-bold">Commentaire (3) :</span> Dans le cas de zone de sismicité très faible (Zone 0 de la carte de zonage sismique, cf. <a href="#rpa-fig-3.1" class="rpa-inline-link">Figure (3.1)</a> &amp; Annexe A), les séismes qui pourraient s'y produire sont estimés avoir de faibles magnitudes ; les calculs de stabilité des constructions aux effets du vent sont jugés suffisants pour y couvrir les effets éventuels des sollicitations d'origine sismique.
        </p>
