    <div id="rpa-art-3.2" class="mt-8" style="scroll-margin-top: 100px;">
        <h2 class="rpa-h2" style="color: #c05621;">3.2 Classification des sites</h2>
        
        <div id="rpa-art-3.2.1" style="scroll-margin-top: 100px;">
            <h3 class="rpa-h3">3.2.1 Catégories et critères de classification</h3>
            <p class="text-justify mb-4">
                Des études géotechniques appropriées doivent être réalisées (cf. Annexe B) en vue de classer le site.
            </p>
            <p class="text-justify mb-4">
                Les sites sont classés en cinq (05) catégories en fonction des propriétés mécaniques des sols qui les constituent, cf. Tableau (3.2).
            </p>
            <p class="text-justify mb-4">
                Les quatre (04) premières catégories, sont établies en se basant sur la moyenne des propriétés de sol sur une profondeur minimale de 30 mètres. L'autre catégorie, considérée comme exceptionnelle, concerne les sites nécessitant des investigations spécifiques (S<sub>5</sub>) (cf. &sect; 3.2.2 & 3.2.3).
            </p>

            <div class="space-y-6 mt-6">
                <div>
                    <p class="font-bold">Catégorie S<sub>1</sub> (site rocheux) :</p>
                    <p class="text-justify leading-relaxed">
                        Rocher ou autre formation géologique de ce type pouvant comporter une couche superficielle moins résistante (sable très dense, dense ou moyennement dense, de graviers, d'argile très rigide ou rigide) d'épaisseur inférieure à 5 m et caractérisée par une vitesse moyenne d'onde de cisaillement (V<sub>s</sub> > 800 m/s).
                    </p>
                </div>

                <div>
                    <p class="font-bold">Catégorie S<sub>2</sub> (site ferme) :</p>
                    <p class="text-justify leading-relaxed">
                        Dépôts de sables et/ou de graviers très denses ou d'argile surconsolidée de plusieurs dizaines de mètres et caractérisés par une augmentation progressive des propriétés mécaniques avec la profondeur et des vitesses d'ondes de cisaillement (360 m/s < V<sub>s30</sub> &le; 800 m/s).
                    </p>
                </div>

                <div>
                    <p class="font-bold">Catégorie S<sub>3</sub> (site meuble) :</p>
                    <p class="text-justify leading-relaxed">
                        Dépôts épais de sables et de graviers moyennement denses et/ou d'argile moyennement raide de plusieurs dizaines de mètres et caractérisés par des vitesses d'ondes de cisaillement 180 m/s < V<sub>s30</sub> &le; 360 m/s.
                    </p>
                </div>

                <div>
                    <p class="font-bold">Catégorie S<sub>4</sub> (site très meuble) :</p>
                    <p class="text-justify leading-relaxed">
                        Dépôts épais de sables lâches ou dépôts d'argile molle à moyennement raide et caractérisée par des vitesses d'ondes de cisaillement (V<sub>s30</sub> < 180 m/s) ou tout autre profil contenant une couche d'argile molle de plus de 3 m d'épaisseur.
                    </p>
                </div>

                <div>
                    <p class="font-bold">Catégorie S<sub>5</sub> (site nécessitant des investigations approfondies et des études spécifiques) (cf. &sect; 3.2.2 & 3.2.3).</p>
                </div>
            </div>

            <p class="text-justify mt-8 leading-relaxed">
                Par ailleurs, il convient de classer le site selon la valeur moyenne de la vitesse des ondes de cisaillement sur les 30 mètres supérieurs (V<sub>s30</sub>). Ce paramètre est le plus fiable pour la classification du site.
            </p>
            <p class="text-justify mt-4 leading-relaxed">
                En cas d'indisponibilité de V<sub>s</sub>, il convient d'utiliser les valeurs moyennes harmoniques d'autres résultats d'essais (pénétromètre statique, SPT, pressiomètre, etc), données dans le Tableau (3.2). Selon la disponibilité et la fiabilité des résultats de différents types d'essais, le site sera classé dans la catégorie la plus appropriée. En cas de doute, il convient de classer le site dans la catégorie voisine, immédiate, la plus défavorable.
            </p>

            <div class="mt-6 ml-8">
                <p class="text-justify leading-relaxed">
                    (a) La valeur de la vitesse de l'onde de cisaillement du rocher doit être mesurée sur site ou estimée dans le cas d'un rocher peu altéré. Les roches tendres ou altérées peuvent être classées en catégorie S<sub>2</sub> dans le cas où V<sub>s</sub> n'est pas mesurée. Le site ne peut être classé dans la catégorie S<sub>1</sub> s'il existe plus de 3 m de sol entre la surface du rocher et le niveau bas des fondations superficielles.
                </p>
            </div>
        </div>
    </div>
