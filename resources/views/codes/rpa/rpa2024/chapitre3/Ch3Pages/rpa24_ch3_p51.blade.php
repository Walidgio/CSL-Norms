    <div class="rpa-comment-box mt-6 space-y-4">
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (1) :</span> Dans le domaine d'application du présent DTR, le mouvement dû au séisme en un point donné de la surface du sol est représenté par un spectre de réponse élastique en accélération, dénommé par la suite &laquo;spectre de réponse élastique&raquo;.
        </p>
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (2) :</span> Les deux niveaux d'action sismique, décrits en &sect; 1.2.1 et &sect; 1.2.2, sont représentés par une seule forme de spectre de réponse élastique pour l'objectif de non-effondrement (état limite ultime &mdash; action sismique de calcul) et pour l'objectif de limitation des dommages.
        </p>
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (3) :</span> L'action sismique horizontale est décrite par deux composantes orthogonales supposées indépendantes et représentées par le même spectre de réponse.
        </p>
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (4) :</span> Lors du choix de la forme appropriée du spectre, il convient de tenir compte de la magnitude des séismes qui contribuent principalement à l'aléa sismique défini pour l'évaluation probabiliste de l'aléa.
        </p>
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (5) :</span> Lorsque la classe de site est autre que rocheuse (S<sub>1</sub>), il convient de considérer le coefficient de site approprié.
        </p>
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (6) :</span> Des représentations temporelles du mouvement sismique peuvent être utilisées.
        </p>
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (7) :</span> La prise en compte de la variation du mouvement du sol dans l'espace ainsi que dans le temps peut être exigé pour certains types de structure.
        </p>
        <p class="text-justify italic leading-relaxed">
            <span class="font-bold">&bull; Commentaire (8) :</span> Une amplification supplémentaire de l'accélération de zone doit être introduite, par le biais d'un coefficient d'amplification topographique (S<sub>T</sub>), pour les structures situées sur ou à proximité de pentes (cf. <span class="font-bold">Annexe C</span>). Cette amplification supplémentaire est à prendre en considération aussi dans les vérifications de la stabilité de terrains en pente.
        </p>
    </div>

