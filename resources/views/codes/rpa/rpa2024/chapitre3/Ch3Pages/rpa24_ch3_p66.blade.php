    <div class="mt-8">
        <h4 class="font-bold underline">13. Ossatures en portiques avec palées de contreventement à barres centrées</h4>
        <p style="text-align: justify;">
            Dans ces ossatures, la résistance aux forces horizontales est assurée, d'une part, par des portiques et, d'autre part, par des palées de contreventements, agissant dans le même plan.
        </p>
        <p class="italic mt-2">Pour ce système de contreventement, il n'y a pas de limitation, en hauteur, des bâtiments.</p>
        
        <p class="mt-4">Ces ossatures sont classées dans les deux catégories suivantes :</p>
        <div class="mt-2 space-y-4">
            <p style="text-align: justify;">
                <span class="font-bold">(13a) : Palées de contreventement à barres centrées en X</span>, dans lesquelles la résistance aux forces horizontales est assurée uniquement par les diagonales tendues, les diagonales comprimées étant négligées ;
            </p>
            <p style="text-align: justify;">
                <span class="font-bold">(13b) : Palées de contreventement à barres centrées en V</span>, dans lesquelles la résistance aux forces horizontales ne peut être assurée que par la participation conjointe des diagonales tendues et comprimées ; le point d'intersection de ces diagonales est situé sur une membrure horizontale qui doit être continue.
            </p>
            <p style="text-align: justify;">
                Les palées de contreventement à barres centrées en K ne sont pas autorisées, sauf justifications spécifiques probantes.
            </p>
        </div>
    </div>

    <div class="mt-8">
        <h4 class="font-bold underline">14. Système en pendule inversé</h4>
        <p style="text-align: justify;">
            Cette catégorie de système structural de faible degré d'hyperstaticité concerne essentiellement des portiques classiques, à un seul niveau avec une traverse rigide, et des structures élancées de type "tube", où les éléments résistants sont essentiellement des poteaux situés en périphérie de la structure.
        </p>
        <p style="text-align: justify;" class="mt-2">
            Ces structures particulières se traduisent par un comportement dissipatif localisé uniquement aux extrémités des poteaux.
        </p>
    </div>

