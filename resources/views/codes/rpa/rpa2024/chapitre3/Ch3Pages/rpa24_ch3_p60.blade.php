                <div class="rpa-bullet">* Bâtiments d'habitation collective ou à usage de bureaux dont la hauteur ne dépasse pas 48 m ;</div>
                <div class="rpa-bullet">* Autres bâtiments pouvant accueillir au plus 300 personnes simultanément tels que, bâtiments à usage de bureaux, bâtiments industriels, etc ;</div>
                <div class="rpa-bullet">* Parkings de stationnement publics, etc.</div>
            </div>
        </div>
    </div>

    <div class="mt-6">
