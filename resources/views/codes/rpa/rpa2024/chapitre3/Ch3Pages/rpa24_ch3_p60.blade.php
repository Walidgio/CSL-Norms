        <div id="rpa-art-3.4-g1b" class="rpa-bullet">• <b>Groupe 1B : Bâtiments de grande importance</b></div>
        <div class="rpa-indent space-y-2">
            <div class="rpa-bullet">- Bâtiments abritant fréquemment de grands rassemblements de personnes :</div>
            <div class="rpa-indent space-y-1">
                <div class="rpa-bullet">* Bâtiments recevant du public et pouvant accueillir simultanément plus de 300 personnes tels que grande mosquée, bâtiments à usage de bureaux, bâtiments industriels et commerciaux, universitaires, constructions sportives et culturelles, pénitenciers, grands hôtels ;</div>
                <div class="rpa-bullet">* Bâtiments d'habitation collective ou à usage de bureaux dont la hauteur dépasse 48 m.</div>
            </div>
            <div class="rpa-bullet">- Bâtiments publics d'intérêt national ou ayant une importance socio-culturelle et économique certaine :</div>
            <div class="rpa-indent space-y-1">
                <div class="rpa-bullet">* Bâtiments de bibliothèque ou d'archives d'importance régionale, musée, etc ;</div>
                <div class="rpa-bullet">* Bâtiments des établissements sanitaires autres que ceux du groupe 1A ;</div>
                <div class="rpa-bullet">* Bâtiments de centres de production ou de distribution d'énergie autres que ceux du groupe 1A ;</div>
                <div class="rpa-bullet">* Châteaux d'eau et réservoirs.</div>
            </div>
            <div class="rpa-bullet">- Bâtiments scolaires quelque soit leur taille</div>
        </div>
    </div>

    <div class="mt-6">
